# Regenerate gen/<tag>/ for every module in modules.json, then gen/modules.c listing them and gen/import_hle.c.
# Usage: python tools/gen_all.py <game System dir> <ida export dir> [tag ...]
import json, sys, os, subprocess, concurrent.futures
sysdir, expdir = sys.argv[1], sys.argv[2]
only = set(sys.argv[3:])
here = os.path.dirname(os.path.abspath(__file__))
port = os.path.dirname(here)
mods = json.load(open(os.path.join(port, 'modules.json')))['modules']

def run(m):
    out = os.path.join(port, 'gen', m['tag'])
    if os.path.isdir(out):
        for f in os.listdir(out): os.remove(os.path.join(out, f))
    exp = os.path.join(expdir, os.path.splitext(m['file'])[0] + '.export.json')
    cmd = [sys.executable, os.path.join(here, 'recomp.py'), os.path.join(sysdir, m['file']), exp, out,
           '--config', os.path.join(port, 'recomp_config.json'), '--tag', m['tag'], '--base', hex(m['base']),
           '--modules', os.path.join(port, 'modules.json')]
    r = subprocess.run(cmd, capture_output=True, text=True)
    return m['tag'], r.returncode, (r.stderr or '') + (r.stdout or '')

todo = [m for m in mods if not only or m['tag'] in only]
with concurrent.futures.ThreadPoolExecutor(8) as ex:
    for tag, rc, log in ex.map(run, todo):
        print('==== %s (rc %d)\n%s' % (tag, rc, log.strip()))

with open(os.path.join(port, 'gen', 'modules.c'), 'w') as fp:
    fp.write('// generated by gen_all.py\n#include "recomp.h"\n\n')
    for m in mods: fp.write('extern const RecModule rec_module_%s;\n' % m['tag'])
    fp.write('\nconst RecModule *const rec_modules[] = {\n')
    for m in mods: fp.write('  &rec_module_%s,\n' % m['tag'])
    fp.write('};\nconst int rec_module_count = %d;\n' % len(mods))

# host functions bound to imports (runtime.c: import_hle_lookup), from the config's "all" section
cfg = json.load(open(os.path.join(port, 'recomp_config.json')))
ih = cfg.get('all', {}).get('import_hle', {})
with open(os.path.join(port, 'gen', 'import_hle.c'), 'w') as fp:
    fp.write('// generated by gen_all.py from recomp_config.json\n#include "recomp.h"\n#include <strings.h>\n\n')
    for fn in sorted(set(ih.values())): fp.write('void %s(void);\n' % fn)
    fp.write('\nstatic const struct { const char *dll, *name; GFunc fn; } tab[] = {\n')
    for k, fn in sorted(ih.items()):
        d, n = k.split('!', 1)
        fp.write('  {"%s", "%s", %s},\n' % (d, n, fn))
    fp.write('};\n\nGFunc import_hle_lookup(const char *dll, const char *name) {\n')
    fp.write('    for (unsigned i = 0; i < sizeof tab / sizeof *tab; i++)\n')
    fp.write('        if (!strcasecmp(tab[i].dll, dll) && !strcmp(tab[i].name, name)) return tab[i].fn;\n')
    fp.write('    return 0;\n}\n')
